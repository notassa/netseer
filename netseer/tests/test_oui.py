MANUF = """# This file was generated by TShark 5.1.0 with the
# command `tshark -G manuf`.
00:00:0C\tCisco\tCisco Systems, Inc
00:1B:C5\tIEEEReg\tIEEE Registration Authority
00:1B:C5:00:10/36\tOpenRBcomDir\tOpenRB.com, Direct SIA
00:50:56\tVMware\tVMware, Inc.
"""


@pytest.fixture
def manuf(tmp_path, monkeypatch):
    path = tmp_path / "manuf"
    path.write_text(MANUF)
    monkeypatch.setattr(oui, "MANUF_PATH", path)
    oui._manuf.cache_clear()
    yield path
    oui._manuf.cache_clear()


def test_manuf_longest_block_wins_then_ieee_fallback(manuf, tmp_path):
    ieee = tmp_path / "oui.csv"
    ieee.write_text("Registry,Assignment,Organization Name,Organization Address\nMA-L,A8BBCC,Ieee Only Ltd,x\n")
    assert oui.vendor_for("00:1b:c5:00:10:99", ieee) == "OpenRB.com, Direct SIA"       # 36-bit block
    assert oui.vendor_for("00:1b:c5:00:20:99", ieee) == "IEEE Registration Authority"  # falls back to /24
    assert oui.vendor_for("00:50:56:a5:24:c2", ieee) == "VMware, Inc."
    assert oui.vendor_for("a8:bb:cc:00:00:01", ieee) == "Ieee Only Ltd"                # not in manuf
    assert oui.vendor_for("02:1a:c5:00:00:00", ieee) == oui.PRIVATE_MAC
    info = oui.manuf_info()
    assert info["entries"] == 4 and info["generator"] == "TShark 5.1.0"


def test_update_keeps_old_list_when_download_is_broken(manuf, monkeypatch):
    def get(url, timeout, follow_redirects):
        return httpx.Response(200, text="# empty\n", request=httpx.Request("GET", url))
    monkeypatch.setattr(oui.httpx, "get", get)
    with pytest.raises(ValueError):
        oui.update_manuf()
    assert manuf.read_text() == MANUF


def test_update_stores_list_dated_by_last_modified(manuf, monkeypatch):
    big = MANUF + "".join(f"{i >> 16:02X}:{(i >> 8) & 255:02X}:{i & 255:02X}\tV{i}\tVendor {i}\n"
                          for i in range(0x100000, 0x100000 + oui.MANUF_MIN_ROWS))
    def get(url, timeout, follow_redirects):
        return httpx.Response(200, text=big, headers={"Last-Modified": "Wed, 21 Oct 2026 10:40:04 GMT"},
                              request=httpx.Request("GET", url))
    monkeypatch.setattr(oui.httpx, "get", get)
    assert oui.update_manuf() == oui.MANUF_MIN_ROWS + 4
    assert int(os.stat(manuf).st_mtime) == 1792579204


def test_parse_sll_line():
    line = ("06:35:54.956536  In 02:1a:c5:00:00:00 ethertype IPv4 (0x0800), length 68: 59.166.0.4.56279 > "
            "149.171.126.4.61997: Flags [.], ack 1, length 0")
    assert oui.parse_sll_line(line) == ("59.166.0.4", "02:1a:c5:00:00:00")
    icmp = "06:35:55.1 Out 00:50:56:a5:24:c2 ethertype IPv4 (0x0800), length 88: 10.0.0.5 > 10.0.0.1: ICMP echo"
    assert oui.parse_sll_line(icmp) == ("10.0.0.5", "00:50:56:a5:24:c2")
    assert oui.parse_sll_line("06:35:55.1 Out 00:50:56:a5:24:c2 ethertype ARP (0x0806), length 44: Request") is None


def _sll_packet(mac: bytes, src: str, dst: str) -> bytes:
    ip = struct.pack("!BBHHHBBH4s4s", 0x45, 0, 28, 1, 0, 64, 17, 0, bytes(map(int, src.split("."))),
                     bytes(map(int, dst.split("."))))
    frame = struct.pack("!HHH8sH", 0, 1, 6, mac + b"\0\0", 0x0800) + ip + struct.pack("!HHHH", 1000, 53, 8, 0)
    return struct.pack("<IIII", 0, 0, len(frame), len(frame)) + frame


@pytest.mark.skipif(not shutil.which("tcpdump"), reason="tcpdump not installed")
def test_sll_macs_reads_sender_mac_per_ip(tmp_path):
    cap = tmp_path / "sll.pcap"
    pkts = [_sll_packet(bytes.fromhex("005056a524c2"), "10.0.0.5", "10.0.0.1")] * 3 + \
           [_sll_packet(bytes.fromhex("001b17059e1c"), "10.0.0.5", "10.0.0.1"),        # routed once: minority
            _sll_packet(bytes.fromhex("001b17059e1c"), "10.0.0.1", "10.0.0.5")]
    cap.write_bytes(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 113) + b"".join(pkts))
    assert oui.sll_macs(cap) == {"10.0.0.5": "00:50:56:a5:24:c2", "10.0.0.1": "00:1b:17:05:9e:1c"}
    routed = [_sll_packet(bytes.fromhex("001b17059e1c"), f"149.171.126.{i}", "10.0.0.5") for i in range(3)]
    cap.write_bytes(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 113) + b"".join(pkts + routed))
    assert oui.sll_macs(cap) == {"10.0.0.5": "00:50:56:a5:24:c2"}               # router MAC for 4 IPs: dropped
    eth = tmp_path / "eth.pcap"
    eth.write_bytes(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 1))   # Ethernet: Suricata has the MACs
    assert oui.sll_macs(eth) == {}


def test_online_vendor_fills_unknown_and_caches(conn):  # noqa: F811
    conn.execute("INSERT INTO devices(analysis_id, ip, mac) VALUES (1, '10.0.0.5', 'f0:1f:af:00:00:01')")
    calls = []

    def get(url, headers=None, timeout=None):
        calls.append(url)
        return httpx.Response(200, json={"success": True, "found": True, "company": "Acme"},
                              request=httpx.Request("GET", url))

    assert oui.online_vendors(conn, 1, get=get) == 1
    assert conn.execute("SELECT vendor FROM devices WHERE ip = '10.0.0.5'").fetchone()[0] == "Acme"
    assert calls == ["https://api.maclookup.app/v2/macs/F01FAF"]
    assert oui.online_vendors(conn, 1, get=get) == 0                              # vendor now filled: nothing to ask
    assert calls == ["https://api.maclookup.app/v2/macs/F01FAF"]                  # no second call


