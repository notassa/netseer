def test_online_vendor_not_found_is_cached(conn):  # noqa: F811
    conn.execute("INSERT INTO devices(analysis_id, ip, mac) VALUES (1, '10.0.0.10', 'f0:1f:af:00:00:01')")
    calls = []

    def get(url, headers=None, timeout=None):
        calls.append(url)
        return httpx.Response(200, json={"success": True, "found": False, "company": ""},
                              request=httpx.Request("GET", url))

    assert oui.online_vendors(conn, 1, get=get) == 0
    assert conn.execute("SELECT vendor FROM devices WHERE ip = '10.0.0.10'").fetchone()[0] is None
    assert oui.online_vendors(conn, 1, get=get) == 0
    assert calls == ["https://api.maclookup.app/v2/macs/F01FAF"]                  # only the first run asked
    cached = conn.execute("SELECT result_json FROM ti_cache WHERE indicator = 'maclookup:F01FAF'").fetchone()
    assert cached and json.loads(cached[0]) == {"found": False, "company": ""}
